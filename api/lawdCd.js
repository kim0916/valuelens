// 초성 매핑
const CHO_MAP = {
  "ㄱ": ["가","나","다"].slice(0,1).map(()=>"가").join(""), // 가 ~ 나 미만
};
const CHO_RANGES = [
  ["ㄱ", 0xAC00, 0xB097], ["ㄴ", 0xB098, 0xB2E3], ["ㄷ", 0xB2E4, 0xB527],
  ["ㄹ", 0xB528, 0xB77B], ["ㅁ", 0xB77C, 0xB9C7], ["ㅂ", 0xB9C8, 0xBC13],
  ["ㅅ", 0xBC14, 0xBE5F], ["ㅇ", 0xBE60, 0xC0AB], ["ㅈ", 0xC0AC, 0xC2F7],
  ["ㅊ", 0xC2F8, 0xC543], ["ㅋ", 0xC544, 0xC78F], ["ㅌ", 0xC790, 0xC9DB],
  ["ㅍ", 0xC9DC, 0xCC27], ["ㅎ", 0xCC28, 0xCE73],
];

function matchCho(str, cho) {
  const range = CHO_RANGES.find(([c]) => c === cho);
  if (!range) return false;
  const code = str.charCodeAt(0);
  return code >= range[1] && code < range[2] + 588;
}

function fuzzyMatch(text, query) {
  if (!query) return true;
  const q = query.trim();
  const t = text.replace(/\s/g, "");
  // 초성 검색
  if (q.length === 1 && /[ㄱ-ㅎ]/.test(q)) return matchCho(t, q);
  // 부분 일치
  return t.includes(q.replace(/\s/g, ""));
}

export default function handler(req, res) {
  if (req.method !== "POST") { res.status(405).json({ error: "POST만 허용" }); return; }

  const { type, sido, sigungu, region, dong } = req.body || {};

  // ── 시/도 목록 ──
  if (type === "sido") {
    res.status(200).json({ list: Object.keys(REGION_DATA) });
    return;
  }

  // ── 시/도 → 구/군 목록 ──
  if (type === "sigungu") {
    const list = sido ? Object.keys(REGION_DATA[sido] || {}) : [];
    res.status(200).json({ list });
    return;
  }

  // ── 구/군 → 동 목록 ──
  if (type === "dong") {
    const sidoData = REGION_DATA[sido] || {};
    const gunguData = sidoData[sigungu] || {};
    const list = gunguData.dongs || [];
    res.status(200).json({ list });
    return;
  }

  // ── type:"lawdCd" — sigungu → lawdCd 변환 (LocationPicker용) ──
  if (type === "lawdCd") {
    const sg = sigungu || region || "";
    if (sido && REGION_DATA[sido] && REGION_DATA[sido][sg]) {
      res.status(200).json({ lawdCd: REGION_DATA[sido][sg].code, matched: sg });
      return;
    }
    for (const sidoKey of Object.keys(REGION_DATA)) {
      if (REGION_DATA[sidoKey][sg]) {
        res.status(200).json({ lawdCd: REGION_DATA[sidoKey][sg].code, matched: sg });
        return;
      }
    }
    res.status(404).json({ error: `"${sg}" 코드를 찾을 수 없습니다.` });
    return;
  }

  // ── 구/군 → lawdCd 변환 ──
  const target = sigungu || region || "";
  if (!target) { res.status(400).json({ error: "sigungu 또는 region 필수" }); return; }

  // 시도 힌트 있으면 정확히 매핑
  if (sido && REGION_DATA[sido]) {
    const entry = REGION_DATA[sido][target];
    if (entry) {
      res.status(200).json({ lawdCd: entry.code, matched: target });
      return;
    }
  }

  // 전체 검색
  for (const sidoKey of Object.keys(REGION_DATA)) {
    const entry = REGION_DATA[sidoKey][target];
    if (entry) {
      res.status(200).json({ lawdCd: entry.code, matched: target });
      return;
    }
  }

  res.status(404).json({ error: `"${target}" 법정동 코드를 찾을 수 없습니다.` });
}
