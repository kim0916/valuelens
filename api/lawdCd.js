// 중구/동구/서구 등 중복 구 → 시도 힌트로 구분
const SIDO_CODE = {
  "서울":"11","경기":"41","인천":"28","부산":"26","대구":"27","광주":"29","대전":"30","울산":"31","세종":"36","충북":"43","충남":"44","전북":"45","전남":"46","경북":"47","경남":"48","제주":"50",
};

function normalize(s) { return String(s||"").replace(/\s/g,""); }

export default function handler(req, res) {
  if (req.method !== "POST") { res.status(405).json({ error:"POST만 허용" }); return; }

  const { type, sido, region, dong } = req.body || {};

  // ── 시/도 목록 반환 ──
  if (type === "sido") {
    res.status(200).json({ list: Object.keys(SIDO_MAP) });
    return;
  }

  // ── 시/도 → 구/군 목록 반환 ──
  if (type === "sigungu") {
    const list = SIDO_MAP[sido] || [];
    res.status(200).json({ list });
    return;
  }

  // ── 구/군 → lawdCd 변환 ──
  const sigungu = normalize(region || "");
  let lawdCd = null;

  // 1. 직접 매핑
  for (const [k, v] of Object.entries(LAWD_MAP)) {
    if (normalize(k) === sigungu) { lawdCd = v; break; }
  }

  // 2. 시도 힌트로 중복 구 구분
  if (!lawdCd && sido) {
    const prefix = SIDO_CODE[sido];
    for (const [k, v] of Object.entries(LAWD_MAP)) {
      if (normalize(k) === sigungu && prefix && v.startsWith(prefix)) { lawdCd = v; break; }
    }
  }

  // 3. 부분 일치
  if (!lawdCd) {
    for (const [k, v] of Object.entries(LAWD_MAP)) {
      if (normalize(k).includes(sigungu) || sigungu.includes(normalize(k))) { lawdCd = v; break; }
    }
  }

  if (lawdCd) {
    res.status(200).json({ lawdCd, matched: region });
  } else {
    res.status(404).json({ error:`"${region}" 코드를 찾을 수 없습니다.` });
  }
}
