function normalize(s) {
  return String(s || "").replace(/\s/g, "");
}

function extractSigungu(region) {
  let r = normalize(region);
  // 시도 접두어 제거
  for (const p of SIDO_PREFIX) {
    if (r.startsWith(normalize(p))) {
      r = r.slice(normalize(p).length);
      break;
    }
  }
  return r;
}

export default function handler(req, res) {
  if (req.method !== "POST") { res.status(405).json({ error: "POST만 허용" }); return; }

  const { region, dong } = req.body || {};
  if (!region) { res.status(400).json({ error: "region 필수" }); return; }

  const sigungu = extractSigungu(region);

  // 1. 정확히 일치
  let lawdCd = LAWD_MAP[sigungu];

  // 2. 부분 일치 (앞에서부터)
  if (!lawdCd) {
    const keys = Object.keys(LAWD_MAP);
    const found = keys.find(k => normalize(k) === sigungu) ||
                  keys.find(k => normalize(k).startsWith(sigungu)) ||
                  keys.find(k => sigungu.startsWith(normalize(k)));
    if (found) lawdCd = LAWD_MAP[found];
  }

  // 3. dong 정보로 구 구분 (동 이름에 구 힌트가 있을 때)
  if (!lawdCd && dong) {
    const d = normalize(dong);
    const keys = Object.keys(LAWD_MAP);
    const found = keys.find(k => normalize(k).includes(d.slice(0, 2)));
    if (found) lawdCd = LAWD_MAP[found];
  }

  if (lawdCd) {
    res.status(200).json({ lawdCd, matched: sigungu });
  } else {
    res.status(404).json({ error: `"${region}" 법정동 코드를 찾을 수 없습니다.`, sigungu });
  }
}
